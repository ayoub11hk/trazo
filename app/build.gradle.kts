// Backend settings come from local.properties or environment variables (CI secrets).
// Both values are public by design (the anon key is protected by row-level security);
// if they are missing the app asks for them on first launch.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun cfg(name: String): String = (localProps.getProperty(name) ?: System.getenv(name) ?: "").trim()

// Optional release signing: keystore.properties (never committed) or CI secrets.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signing(name: String): String? = keystoreProps.getProperty(name) ?: System.getenv(name)

